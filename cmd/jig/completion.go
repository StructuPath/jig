// completion.go — `jig completion zsh|bash|fish`: a static completion script
// for every command, subcommand, and flag. The script is generated from the
// command table (main.go) and from each command's own flag set, read through
// parseFlags' probe, so it cannot drift from what the binary accepts.
package main

import (
	"context"
	"flag"
	"fmt"
	"io"
	"sort"
	"strings"
)

const completionUsage = `Usage: jig completion zsh|bash|fish

Print a shell completion script for jig's commands, subcommands, and flags.

  zsh:   jig completion zsh > "${fpath[1]}/_jig"   (then restart the shell)
  bash:  source <(jig completion bash)             (or save it under
                                                    bash-completion's
                                                    completions directory)
  fish:  jig completion fish > ~/.config/fish/completions/jig.fish

Exit codes:
  0  the script was printed
  2  usage error
`

// completionNode is what the shell offers after one command path: its
// subcommands and its flags.
type completionNode struct {
	command string // "def", or "" for jig itself
	verb    string // "invoke", or "" for the command itself
	words   []string
	flags   []string
}

func completionCommand(_ context.Context, args []string, stdout, stderr io.Writer) int {
	if len(args) == 1 && (args[0] == "-h" || args[0] == "--help" || args[0] == "help") {
		fmt.Fprint(stdout, completionUsage)
		return exitAccepted
	}
	if len(args) != 1 {
		return usageError(stderr, "jig completion", "exactly one shell is required", completionUsage)
	}
	nodes := completionTree()
	switch args[0] {
	case "zsh":
		fmt.Fprint(stdout, zshCompletion(nodes))
	case "bash":
		fmt.Fprint(stdout, bashCompletion(nodes))
	case "fish":
		fmt.Fprint(stdout, fishCompletion(nodes))
	default:
		return usageError(stderr, "jig completion",
			fmt.Sprintf("unknown shell %q; use zsh, bash, or fish", args[0]), completionUsage)
	}
	return exitAccepted
}

// completionTree walks the command table: the top-level words, then each
// command and each of its verbs with the flags its flag set defines.
func completionTree() []completionNode {
	top := completionNode{}
	var nodes []completionNode
	for _, entry := range commands {
		top.words = append(top.words, entry.name)
		node := completionNode{command: entry.name}
		for _, verb := range entry.verbs {
			node.words = append(node.words, verb.name)
			nodes = append(nodes, completionNode{
				command: entry.name, verb: verb.name,
				flags: probeFlags(verb.run, nil),
			})
		}
		// A family dispatcher parses no flags of its own; the worker parses
		// its own when the first argument is not a verb.
		node.flags = probeFlags(entry.run, nil)
		nodes = append(nodes, node)
	}
	return append([]completionNode{top}, nodes...)
}

// probeFlags runs a command with the flag probe set and returns the flags
// its flag set defines, as --name, sorted. A command that returns before it
// parses flags (a dispatcher with no verb, `version`) defines none.
func probeFlags(run func(context.Context, []string, io.Writer, io.Writer) int, args []string) []string {
	var names []string
	probe := func(flags *flag.FlagSet) {
		flags.VisitAll(func(f *flag.Flag) { names = append(names, "--"+f.Name) })
	}
	flagProbe.Store(&probe)
	defer flagProbe.Store(nil)
	run(context.Background(), args, io.Discard, io.Discard)
	sort.Strings(names)
	return names
}

// shellCase is the case arms bash and zsh share: the most specific path
// first, so `def invoke` is matched before `def <anything>`.
func shellCase(nodes []completionNode) string {
	var arms strings.Builder
	for _, node := range nodes {
		if node.command == "" || node.verb == "" {
			continue
		}
		fmt.Fprintf(&arms, "    %q) candidates=%q ;;\n",
			node.command+" "+node.verb, strings.Join(node.flags, " "))
	}
	for _, node := range nodes {
		if node.command == "" || node.verb != "" {
			continue
		}
		fmt.Fprintf(&arms, "    %q*) candidates=%q ;;\n",
			node.command+" ", strings.Join(append(append([]string{}, node.words...), node.flags...), " "))
	}
	return arms.String()
}

func topWords(nodes []completionNode) string {
	return strings.Join(append(append([]string{}, nodes[0].words...), "help"), " ")
}

func bashCompletion(nodes []completionNode) string {
	return `# bash completion for jig — generated by: jig completion bash
_jig() {
  local cur=${COMP_WORDS[COMP_CWORD]} candidates=""
  if [[ $COMP_CWORD -eq 1 ]]; then
    candidates="` + topWords(nodes) + `"
  else
    local verb=""
    [[ $COMP_CWORD -gt 2 ]] && verb=${COMP_WORDS[2]}
    case "${COMP_WORDS[1]} $verb" in
` + shellCase(nodes) + `    esac
  fi
  COMPREPLY=($(compgen -W "$candidates" -- "$cur"))
}
complete -o default -F _jig jig
`
}

func zshCompletion(nodes []completionNode) string {
	return `#compdef jig
# zsh completion for jig — generated by: jig completion zsh
_jig() {
  local candidates=""
  if (( CURRENT == 2 )); then
    candidates="` + topWords(nodes) + `"
  else
    local verb=""
    (( CURRENT > 3 )) && verb=$words[3]
    case "$words[2] $verb" in
` + shellCase(nodes) + `    esac
  fi
  compadd -- ${=candidates}
  (( CURRENT > 2 )) && _files
}
if [[ $zsh_eval_context[-1] == loadautofunc ]]; then
  _jig "$@"
else
  compdef _jig jig
fi
`
}

func fishCompletion(nodes []completionNode) string {
	var script strings.Builder
	script.WriteString("# fish completion for jig — generated by: jig completion fish\n")
	fmt.Fprintf(&script, "complete -c jig -n __fish_use_subcommand -a %q\n", topWords(nodes))
	for _, node := range nodes {
		if node.command == "" {
			continue
		}
		if node.verb == "" {
			if len(node.words) > 0 {
				fmt.Fprintf(&script,
					"complete -c jig -n '__fish_seen_subcommand_from %s; and not __fish_seen_subcommand_from %s' -a %q\n",
					node.command, strings.Join(node.words, " "), strings.Join(node.words, " "))
			}
			condition := "__fish_seen_subcommand_from " + node.command
			if len(node.words) > 0 {
				condition += "; and not __fish_seen_subcommand_from " + strings.Join(node.words, " ")
			}
			writeFishFlags(&script, condition, node.flags)
			continue
		}
		writeFishFlags(&script,
			"__fish_seen_subcommand_from "+node.command+"; and __fish_seen_subcommand_from "+node.verb,
			node.flags)
	}
	return script.String()
}

func writeFishFlags(script *strings.Builder, condition string, flags []string) {
	for _, name := range flags {
		fmt.Fprintf(script, "complete -c jig -n '%s' -l %s\n", condition, strings.TrimPrefix(name, "--"))
	}
}
